#!/usr/bin/env python3
"""Guards the knowledge layer: is it still true, and is it still small.

    scripts/harness context            # report both
    scripts/harness context check      # exit 1 if a doc is stale or the budget is blown
    scripts/harness context bless      # re-record hashes after updating a doc
    scripts/harness context digest     # everything the librarian pass needs to read
    scripts/harness context spend      # what recent sessions actually cost, per session

Two failures this catches, both of which shipped before it existed:

A doc goes stale because something *else* changed — the skill describing
verify.sh stops being true when verify.sh grows a step, and the stale file never
appears in the diff, so no diff-scoped review can see it. A doc declares what it
describes with a `tracks:` comment, and the hashes live in .claude/context.lock.

And the always-loaded context only ever grows. Nothing argued against a longer
CLAUDE.md at the moment it was being written, which is the only moment the
argument is cheap.
"""

import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from harness_paths import HARNESS, ROOT, harness_script

PROJECT_LOCK = ROOT / ".claude/context.lock"
SHARED_LOCK = HARNESS / ".claude/context.lock"


def project_docs():
    """The project's own docs, tracked ROOT-relative against the project's
    lock. AGENTS.local.md only when the project has one — it is a seed the
    project owns."""
    docs = [ROOT / "CLAUDE.md", ROOT / "AGENTS.md"]
    if (ROOT / "AGENTS.local.md").exists():
        docs.append(ROOT / "AGENTS.local.md")
    return docs


def _carries_tracks(doc):
    """Whether a doc declares tracked sources. Agent prompts join the shared
    set only when one does — listing a trackless file would move the doc count
    without checking anything."""
    try:
        text = doc.read_text(errors="replace")
    except OSError:
        return False
    return re.search(r"<!--\s*tracks:", text) is not None


def wiki_pages():
    """The project's wiki pages carrying tracks: — project-owned data,
    generated by scripts/build-wiki.sh from bd and the handoffs. Tracked with
    sources resolved against HARNESS (the generator lives there), recorded in
    the project lock under harness/wiki/<name>."""
    d = ROOT / "harness/wiki"
    if not d.is_dir():
        return []
    try:
        return sorted(p for p in d.glob("*.md") if _carries_tracks(p))
    except OSError:
        return []


def wiki_key(page):
    return "harness/wiki/" + page.name


def wiki_missing(lock):
    """Lock entries for wiki pages whose file no longer exists. Staleness
    iterates existing files only, so without this a deleted page stays blessed
    and silent."""
    return sorted(k for k in lock
                  if k.startswith("harness/wiki/") and not (ROOT / k).exists())


def wiki_untracked(lock):
    """Lock-listed wiki files whose current content carries no tracks: line —
    a page that lost its tracks declaration reads as trackless to every other
    pass, so without this its lock entry survives as a ghost and check stays
    green over a stale hash."""
    return sorted(k for k in lock
                  if k.startswith("harness/wiki/") and (ROOT / k).exists()
                  and not _carries_tracks(ROOT / k))


def wiki_threshold():
    """The brief's WIKI_MAX_KEYS, read off the brief the project actually
    runs — its own shadow first, the shared copy behind it. None when the
    brief predates the wiki."""
    try:
        text = harness_script("brief.sh").read_text(errors="replace")
    except OSError:
        return None
    m = re.search(r"^WIKI_MAX_KEYS=(\d+)", text, re.M)
    return int(m.group(1)) if m else None


# The shared docs, read from the harness checkout and tracked HARNESS-relative
# against the harness lock. Agent prompts only when one actually declares
# tracked sources — none do today, so the installed-copy lock is unchanged.
SHARED_DOCS = [HARNESS / ".claude/HARNESS.md",
               *sorted((HARNESS / ".claude/skills").glob("*/SKILL.md")),
               *(a for a in sorted((HARNESS / ".claude/agents").glob("*.md"))
                 if _carries_tracks(a))]


def shared_included():
    """Whether the shared docs are checked. Only when the harness checkout is
    this project or sits inside it (the starter) — a project running by
    reference must not fail on a checkout it doesn't own."""
    try:
        HARNESS.resolve().relative_to(ROOT.resolve())
        return True
    except ValueError:
        return False


# The memory index loads every session too, but it lives outside the repo, under
# a directory named for this checkout's path. Absent on another machine, which
# is why it's counted only when it's there rather than assumed.
MEMORY_INDEX = (Path.home() / ".claude/projects"
                / str(ROOT).replace("/", "-") / "memory/MEMORY.md")

# Claude Code's own session transcripts, beside that memory directory. They
# record what each turn actually cost, which is the only place the *whole*
# session floor is visible: the docs below are a measurable 4k, and a real
# session opens at ~54k. The other 50k is Claude Code's system prompt, its tool
# schemas and whatever MCP connectors the app has enabled — none of it in this
# repo, none of it countable by reading files, and all of it re-sent every turn.
TRANSCRIPTS = MEMORY_INDEX.parent.parent


# Every settings file whose SessionStart hooks fire in a session here — Claude
# Code merges all three. `bd setup claude --global` writes to the first, so a
# check that read only the project file would vouch for a clean session while
# the hook ran from the user's home directory.
SETTINGS = [Path.home() / ".claude/settings.json",
            ROOT / ".claude/settings.json",
            ROOT / ".claude/settings.local.json"]

# What the harness installs. Anything else there is always-loaded context nobody
# is counting — and generators put it there: `bd setup claude` writes a
# `bd prime` hook (~1900 tokens) beside the brief that exists to replace it,
# every time it runs. Matched by name rather than executed; a checker that ran
# whatever it found configured would be a worse idea than the drift it catches.
OWN_HOOKS = ("scripts/brief.sh", "scripts/dashboard.py",
             "scripts/harness session", "scripts/harness dashboard")


def _is_own_hook(command):
    """Whether a SessionStart command is one the harness installed. Matched by
    path with boundaries, not substring: a custom `scripts/harness session-extra`
    or `my-scripts/harness session` is foreign cost the budget must not hide."""
    for own in OWN_HOOKS:
        if re.search(r"(?<![\w-])" + re.escape(own) + r"(?![\w/-])", command):
            return True
    return False


def foreign_hooks():
    """(settings file, command) for every SessionStart hook the harness didn't
    install. A file that won't parse is reported rather than skipped: this check
    exists to fail loud, and failing open on a broken settings file is the one
    outcome it can't afford."""
    found = []
    for path in SETTINGS:
        if not path.exists():
            continue
        try:
            settings = json.loads(path.read_text(errors="replace"))
        except (OSError, ValueError) as broken:
            found.append((path, f"unreadable: {broken}"))
            continue
        for entry in settings.get("hooks", {}).get("SessionStart", []):
            for hook in entry.get("hooks", []):
                command = hook.get("command", "").strip()
                if not _is_own_hook(command):
                    found.append((path, command or "(entry with no command)"))
    return found


def stray_beads_blocks():
    """bd writes its managed guidance into every agent-instructions file it
    finds, so a plain install ends up with the same text three times. One copy
    survives, in AGENTS.md, because that is the file every agent reads."""
    strays = []
    for doc in (ROOT / "CLAUDE.md", ROOT / "AGENTS.md"):
        if not doc.exists():
            continue
        try:
            blocks = doc.read_text(errors="replace").count("<!-- BEGIN BEADS")
        except (OSError, UnicodeDecodeError) as exc:
            # Unreadable like missing, but loud: silence would read as clean.
            print(f"  ! {doc} unreadable ({exc}) — skipped", file=sys.stderr)
            continue
        allowed = 1 if doc.name == "AGENTS.md" else 0
        if blocks > allowed:
            strays.append((doc, blocks))
    return strays


def where(path):
    """Settings files live both inside the checkout and in the user's home."""
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path).replace(str(Path.home()), "~", 1)


def tokens(text):
    return round(len(text) / 4)


def sha(path):
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()[:16] if path.exists() else ""
    except OSError:
        # Unreadable like missing for the staleness compare; the budget warns.
        return ""


def tracked_by(doc, base):
    """The sources a doc claims to describe, declared inside the doc itself so
    the mapping can't drift away from the thing it maps. Resolved against base:
    ROOT for project docs, HARNESS for shared ones. A missing or unreadable doc
    claims nothing — the template itself ships no CLAUDE.md."""
    try:
        text = doc.read_text(errors="replace")
    except OSError:
        return []
    m = re.search(r"<!--\s*tracks:(.*?)-->", text, re.S)
    return [base / p for p in m.group(1).split()] if m else []


def load_lock(lock):
    try:
        return json.loads(lock.read_text())
    except Exception:
        return {}


def _relative_key(base):
    """The default lock key as an explicit capability: a doc's path relative
    to the base it is tracked against."""
    return lambda doc: str(doc.relative_to(base))


def staleness(docs, base, lock, keyfn):
    """Docs whose sources moved without them. A doc is only checked once it has
    been blessed — a new doc isn't stale, it's just new. The lock key is a
    required capability the caller supplies; there is no implicit default."""
    stale, unblessed = [], []
    for doc in docs:
        sources = tracked_by(doc, base)
        if not sources:
            continue
        recorded = lock.get(keyfn(doc))
        if recorded is None:
            unblessed.append(doc)
            continue
        moved = [s for s in sources
                 if recorded.get(str(s.relative_to(base))) not in (sha(s), None)]
        if moved and recorded.get("doc") == sha(doc):
            stale.append((doc, moved))
    return stale, unblessed


def turn_costs(transcript):
    """Every turn's full input size, in order. A resumed session replays its
    history with no usage recorded, so zero-cost turns are dropped rather than
    counted as a free session floor."""
    costs = []
    for line in transcript.read_text(errors="replace").splitlines():
        try:
            usage = (json.loads(line).get("message") or {}).get("usage")
        except ValueError:
            continue
        if usage:
            total = (usage.get("input_tokens", 0)
                     + usage.get("cache_creation_input_tokens", 0)
                     + usage.get("cache_read_input_tokens", 0))
            if total:
                costs.append(total)
    return costs


def sessions(limit=12):
    """Recent transcripts, newest last. Bounded because the floor drifts with
    Claude Code releases and connector changes, and a year-old session says
    nothing about what the next one will cost."""
    if not TRANSCRIPTS.is_dir():
        return []
    found = sorted(TRANSCRIPTS.glob("*.jsonl"), key=lambda p: p.stat().st_mtime)
    return [(p, turn_costs(p)) for p in found[-limit:]]


def floor():
    """The median opening context across recent sessions: what a session pays
    before it has done anything. Median rather than mean because one resumed or
    aborted session shouldn't move the number the budget is read against."""
    opens = sorted(c[0] for _, c in sessions() if c)
    return (opens[len(opens) // 2], len(opens)) if opens else (0, 0)


def is_reference():
    """Whether this project runs by reference: the harness lives outside the
    checkout and the project carries no copy of its own.

    scripts/harness ships in every install now, so its presence no longer tells the
    two apart. The copy's own brief.sh does: a reference install keeps no
    shared scripts."""
    try:
        outside = not HARNESS.resolve().is_relative_to(ROOT.resolve())
    except OSError:
        outside = not HARNESS.is_relative_to(ROOT)
    return outside and not (ROOT / "scripts/brief.sh").exists()


def skill_description_tokens(skills_dir):
    """Tokens in every skill description under skills_dir, reading through links.

    One helper for both budget branches, so the copy and reference counts
    can't drift apart: reference installs link each shared skill here."""
    total = 0
    if not skills_dir.is_dir():
        return 0
    try:
        entries = sorted(skills_dir.iterdir())
    except OSError as exc:
        print(f"  ! {skills_dir} unreadable ({exc}) — skill descriptions counted as 0",
              file=sys.stderr)
        return 0
    for entry in entries:
        candidate = entry / "SKILL.md"
        try:
            text = candidate.read_text(errors="replace") if candidate.is_file() else ""
        except (OSError, UnicodeDecodeError) as exc:
            # Unreadable counts as 0, loudly: silence would undercount the load.
            print(f"  ! {candidate} unreadable ({exc}) — counted as 0",
                  file=sys.stderr)
            continue
        if not text:
            continue
        found = re.search(r"^description:\s*(.*)$", text, re.M)
        total += tokens(found.group(1)) if found else 0
    return total


def run_brief():
    """The brief's stdout, via the project-first sibling resolution.

    Never the finder: context.py is a read-only check, and `scripts/harness session`
    links, rewrites .gitignore and may clone. A failed brief is reported on
    stderr rather than silently scored as 0 tokens."""
    try:
        proc = subprocess.run(["bash", str(harness_script("brief.sh"))],
                              capture_output=True, text=True)
    except OSError as exc:
        print(f"  ! brief failed ({exc}) — run scripts/harness brief and read the error",
              file=sys.stderr)
        return ""
    if proc.returncode != 0:
        print(f"  ! brief failed (exit {proc.returncode}) — "
              f"run scripts/harness brief and read the error", file=sys.stderr)
    return proc.stdout


def _wiki_index_part(parts):
    """Append the wiki index cost, when the index exists. One helper for both
    budget branches, so the copy and reference counts cannot drift apart."""
    wiki_index = ROOT / "harness/wiki/index.md"
    if wiki_index.exists():
        try:
            parts.append(("wiki index", tokens(wiki_index.read_text(errors="replace"))))
        except OSError as exc:
            print(f"  ! {wiki_index} unreadable ({exc}) — counted as 0",
                  file=sys.stderr)


def reference_budget():
    """What a by-reference session actually loads: the shared contract the hook
    injects, the brief's output, the stub files here, and the skill
    descriptions through their links."""
    parts = []
    contract = HARNESS / "AGENTS.md"
    if contract.exists():
        try:
            parts.append(("AGENTS.md (contract)", tokens(contract.read_text(errors="replace"))))
        except (OSError, UnicodeDecodeError) as exc:
            print(f"  ! {contract} unreadable ({exc}) — counted as 0",
                  file=sys.stderr)
    for doc in (ROOT / "CLAUDE.md", ROOT / "AGENTS.md"):
        if not doc.exists():
            continue
        try:
            text = doc.read_text(errors="replace")
        except (OSError, UnicodeDecodeError) as exc:
            print(f"  ! {doc} unreadable ({exc}) — counted as 0",
                  file=sys.stderr)
            continue
        name = doc.name + (" stub" if doc.name == "AGENTS.md" else "")
        parts.append((name, tokens(text)))
    parts.append(("session brief", tokens(run_brief())))
    if MEMORY_INDEX.exists():
        try:
            parts.append(("MEMORY.md", tokens(MEMORY_INDEX.read_text(errors="replace"))))
        except (OSError, UnicodeDecodeError) as exc:
            print(f"  ! {MEMORY_INDEX} unreadable ({exc}) — counted as 0",
                  file=sys.stderr)
    _wiki_index_part(parts)
    parts.append(("skill descriptions (via links)",
                  skill_description_tokens(ROOT / ".claude/skills")))
    return parts, sum(n for _, n in parts)


def budget():
    if is_reference():
        return reference_budget()
    brief = run_brief()
    # Both instruction files, because both are always-loaded — CLAUDE.md by
    # Claude Code and AGENTS.md by opencode, and CLAUDE.md imports AGENTS.md so
    # Claude Code pays for both too. Counting only CLAUDE.md would let a session
    # move text into AGENTS.md and watch the number fall while nothing changed.
    # Unreadable like missing, but loud: silence would undercount the load.
    parts = []
    for doc in (ROOT / "CLAUDE.md", ROOT / "AGENTS.md"):
        if not doc.exists():
            continue
        try:
            parts.append((doc.name, tokens(doc.read_text(errors="replace"))))
        except (OSError, UnicodeDecodeError) as exc:
            print(f"  ! {doc} unreadable ({exc}) — counted as 0",
                  file=sys.stderr)
            continue
    parts.append(("session brief", tokens(brief)))
    if MEMORY_INDEX.exists():
        try:
            parts.append(("MEMORY.md", tokens(MEMORY_INDEX.read_text(errors="replace"))))
        except (OSError, UnicodeDecodeError) as exc:
            print(f"  ! {MEMORY_INDEX} unreadable ({exc}) — counted as 0",
                  file=sys.stderr)
    _wiki_index_part(parts)
    parts.append(("skill descriptions",
                  skill_description_tokens(ROOT / ".claude/skills")))
    return parts, sum(n for _, n in parts)


def bless_docs(docs, base, lock, keyfn):
    """Re-record hashes for the docs carrying tracked sources, into an already
    loaded lock. Missing and trackless docs are skipped, and unknown keys are
    kept — so blessing one side never drops the other's entries. The lock key
    is a required capability the caller supplies."""
    for doc in docs:
        sources = tracked_by(doc, base)
        if not sources:
            continue
        lock[keyfn(doc)] = {
            "doc": sha(doc),
            **{str(s.relative_to(base)): sha(s) for s in sources},
        }
    return lock


def show_lock(path):
    """A lock path as the report prints it: project-relative when inside."""
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def write_lock(lock, path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(lock, indent=2, sort_keys=True) + "\n")
    print(f"blessed {len(lock)} docs → {show_lock(path)}")


def bless():
    project_lock = bless_docs(project_docs(), ROOT, load_lock(PROJECT_LOCK),
                              _relative_key(ROOT))
    project_lock = bless_docs(wiki_pages(), HARNESS, project_lock, wiki_key)
    for key in wiki_missing(project_lock) + wiki_untracked(project_lock):
        del project_lock[key]
    if SHARED_LOCK.resolve() == PROJECT_LOCK.resolve():
        # Installed copy: one lock, one line, exactly as today.
        write_lock(bless_docs(SHARED_DOCS, HARNESS, project_lock,
                              _relative_key(HARNESS)), PROJECT_LOCK)
        return
    write_lock(project_lock, PROJECT_LOCK)
    if not shared_included():
        return
    write_lock(bless_docs(SHARED_DOCS, HARNESS, load_lock(SHARED_LOCK),
                          _relative_key(HARNESS)),
               SHARED_LOCK)


def _bd_prefix():
    """The ledger's bead prefix, asked of the ledger itself at runtime — it used
    to be baked into this file at install time, which made every copy differ.

    Read off `bd list`, never `bd config get` or `bd info`: both auto-import a
    stale .beads/issues.jsonl when the ledger looks stale to them, resurrecting
    deleted beads (har-67c). `bd list` never imports."""
    try:
        r = subprocess.run(["bd", "list", "--json", "--all"],
                           capture_output=True, text=True, timeout=10, cwd=ROOT)
        ids = json.loads(r.stdout or "[]")
        got = str((ids[0].get("id", "") if ids else "").split("-", 1)[0]) if ids else ""
        if r.returncode == 0 and re.fullmatch(r"[a-z0-9]{1,10}", got):
            return got
    except Exception:
        pass
    short = re.sub(r"[^a-z0-9]", "", ROOT.name.lower()).lstrip("0123456789")[:3]
    return short or "bd"


def _wiki_digest_lines(entries):
    """The wiki section of the librarian digest. The broad except stays
    inside: the digest serves the librarian, never the gate, so a wiki the
    digest can't read is a line, not a failure."""
    lines = ["\n## Wiki\n"]
    try:
        threshold = wiki_threshold()
        pages = wiki_pages()
        index = ROOT / "harness/wiki/index.md"
        counts = None
        if index.exists():
            m = re.search(r"<!--\s*wiki:\s*topics=(\d+)\s+keys=(\d+)\s*-->",
                          index.read_text(errors="replace"))
            counts = (int(m.group(1)), int(m.group(2))) if m else None
        if threshold is None:
            lines.append("the brief predates the wiki — no threshold to report against\n")
        elif not counts:
            lines.append(f"threshold {threshold} keys; {len(entries)} memories now; "
                         "no index — nothing built yet\n")
        else:
            lines.append(f"threshold {threshold} keys; {len(entries)} memories now; "
                         f"index lists {counts[0]} topics, {counts[1]} keys\n")
        for page in pages:
            try:
                lines.append(f"\n### {page.relative_to(ROOT)}\n{page.read_text(errors='replace')}")
            except (OSError, UnicodeDecodeError) as exc:
                lines.append(f"\n### {page} unreadable ({exc})\n")
    except Exception as exc:
        lines.append(f"unreadable ({exc}) — read harness/wiki/ directly\n")
    return lines


def digest():
    """Everything the librarian reads, in one place, so it doesn't spend its
    context rediscovering the shape of the knowledge layer."""
    out = ["# Knowledge digest\n"]
    parts, total = budget()
    out.append(f"## Always loaded: {total} tokens\n")
    out += [f"- {name}: {n}" for name, n in parts]

    out.append("\n## Skills\n")
    for skill in sorted((ROOT / ".claude/skills").glob("*/SKILL.md")):
        try:
            text = skill.read_text(errors="replace")
        except (OSError, UnicodeDecodeError) as exc:
            out.append(f"\n### {skill.parent.name} unreadable ({exc})\n")
            continue
        found = re.search(r"^description:\s*(.*)$", text, re.M)
        out.append(f"\n### {skill.parent.name} ({tokens(text)} tokens loaded)")
        out.append(f"_{found.group(1) if found else ''}_\n")
        out.append(text.split("---", 2)[-1].strip())

    memories = subprocess.run(["bd", "memories", "--json"],
                              capture_output=True, text=True, cwd=ROOT).stdout
    try:
        entries = {k: v for k, v in json.loads(memories).items() if isinstance(v, str)}
    except Exception:
        entries = {}
    out.append(f"\n## Memories ({len(entries)})\n")
    out += [f"\n### {k}\n{v}" for k, v in sorted(entries.items())]

    out += _wiki_digest_lines(entries)

    packet = Path(f"/tmp/{_bd_prefix()}-knowledge-digest-{os.getpid()}.md")
    packet.write_text("\n".join(out) + "\n")
    print(packet)


def spend():
    """Where a session's tokens went. The floor is fixed and the conversation
    is not, so the two numbers argue for different fixes: a smaller floor, or a
    shorter session. Printed per session because the shape only shows up there
    — the same harness produces a 60k session and a 300k one."""
    print(f"{'session':12}{'turns':>7}{'open':>10}{'peak':>10}{'total in':>12}"
          f"{'floor share':>13}")
    for path, costs in sessions(limit=20):
        if not costs:
            continue
        total = sum(costs)
        print(f"{path.stem[:8]:12}{len(costs):>7}{costs[0]:>10,}{max(costs):>10,}"
              f"{total:>12,}{100 * costs[0] * len(costs) / total:>12.0f}%")
    print("\n  floor share is what the opening context alone costs across the"
          "\n  session — spend above it is conversation, and the fix for each"
          "\n  is different. See .claude/HARNESS.md.")


def show_source(path):
    """A tracked source as the report prints it: project-relative when inside
    the checkout, harness-relative when it lives in the shared copy (wiki
    pages track the generator there), absolute otherwise."""
    for base in (ROOT, HARNESS):
        try:
            return str(path.relative_to(base))
        except ValueError:
            pass
    return str(path)


def report(strict):
    project_lock = load_lock(PROJECT_LOCK)
    stale, unblessed = staleness(project_docs(), ROOT, project_lock,
                                   _relative_key(ROOT))
    wiki_stale, wiki_unblessed = staleness(wiki_pages(), HARNESS,
                                           project_lock, wiki_key)
    stale += wiki_stale
    unblessed += wiki_unblessed
    checked = project_docs() + wiki_pages()
    if shared_included():
        if SHARED_LOCK.resolve() == PROJECT_LOCK.resolve():
            shared_stale, shared_unblessed = staleness(SHARED_DOCS, HARNESS,
                                                       load_lock(PROJECT_LOCK),
                                                       _relative_key(HARNESS))
        else:
            shared_stale, shared_unblessed = staleness(SHARED_DOCS, HARNESS,
                                                       load_lock(SHARED_LOCK),
                                                       _relative_key(HARNESS))
        stale += shared_stale
        unblessed += shared_unblessed
        checked += SHARED_DOCS
    else:
        print("  shared docs skipped (HARNESS outside ROOT) — project docs only;"
              " see .claude/HARNESS.md")
    parts, total = budget()
    failed = False
    missing = wiki_missing(project_lock)
    untracked = wiki_untracked(project_lock)

    for doc, moved in stale:
        failed = True
        names = ", ".join(show_source(s) for s in moved)
        print(f"  STALE {show_source(doc)}")
        print(f"        {names} changed; the doc did not")
    for path, command in foreign_hooks():
        failed = True
        print(f"  HOOK  unaccounted SessionStart hook: {command}")
        print(f"        in {where(path)} — its hooks run in every session here")
        print("        and the cost line below can't see them; see .claude/HARNESS.md")

    for doc, blocks in stray_beads_blocks():
        failed = True
        print(f"  BEADS {show_source(doc)} carries {blocks} bd managed block(s)")
        print("        one copy, in AGENTS.md — see .claude/HARNESS.md")

    # Informational, never a failure: the gate runs before the ledger is pushed
    # by design (verify, commit, then push), so an ahead ledger here is the
    # normal state rather than a broken one. What it must not be is silent.
    try:
        push = subprocess.run(["bash", str(harness_script("ledger-push.sh")),
                               "--check"],
                              capture_output=True, text=True,
                              timeout=30).stdout.strip()
    except Exception:
        push = ""
    for line in push.splitlines():
        print(f"  {line}")

    for doc in unblessed:
        print(f"  new   {show_source(doc)} — run 'scripts/harness context bless'")

    for key in missing:
        failed = True
        print(f"  missing {key} — run 'scripts/harness context bless'")

    for key in untracked:
        failed = True
        print(f"  untracked {key} — tracks removed; run 'scripts/harness context bless'")

    # Reported, never enforced. A threshold here only ever measured how long it
    # had been since someone argued with the layer, and the librarian does that
    # better — so this is a trend line for it to read, not a gate to pass.
    print(f"  cost  {total} tokens every session"
          + " (" + ", ".join(f"{name} {n}" for name, n in parts) + ")")
    measured, seen = floor()
    if measured:
        print(f"  floor {measured:,} tokens before a session does anything"
              f" — {total} of it this repo, {measured - total:,} Claude Code's own")
        print(f"        (median of {seen} recent sessions; re-sent every turn,"
              " so it sets the slope of the whole session)")
    if not stale and not missing and not untracked:
        checked_docs = len(checked)
        print(f"  ok    {checked_docs} docs match the sources they describe")

    return 1 if (failed and strict) else 0


